export type MessageKey = keyof typeof messages.en;

/**
 * Detects the initial supported UI locale.
 * @returns A saved preference or a supported system language.
 */
export function detectLocale(): Locale {
  const saved = localStorage.getItem("notemarkdown:locale");
  if (saved === "en" || saved === "nl") return saved;
  try {
    const settings = JSON.parse(localStorage.getItem("notemarkdown:settings:v1") ?? "{}") as { locale?: unknown };
    if (settings.locale === "en" || settings.locale === "nl") return settings.locale;
  } catch {
    // Invalid legacy preferences fall back to the browser language.
  }
  return navigator.language.toLowerCase().startsWith("nl") ? "nl" : "en";
}

/**
 * Resolves one localized user-facing message.
 * @param locale Active interface locale.
 * @param key Stable message key.
 * @returns Localized text.
 */
export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key];
}
